"""Toolkit provenance of the score-bias kernel benchmark (its kernels themselves need an H100)."""
from scaffolds.transformer.benchmarks import benchmark_score_bias as benchmark


def _toolkit_root(root, version_text):
    ptxas = root / "bin" / "ptxas"
    ptxas.parent.mkdir(parents=True)
    ptxas.write_text(f"#!/bin/sh\necho 'ptxas: NVIDIA (R) Ptx optimizing assembler'\necho '{version_text}'\n"
                     "echo 'Build cuda_12.9.r12.9/compiler.36037853_0'\n")
    ptxas.chmod(0o755)
    return root


def test_reports_record_cuda_home_and_its_ptxas_version(tmp_path, monkeypatch):
    root = _toolkit_root(tmp_path / "nvidia" / "cuda_nvcc", "Cuda compilation tools, release 12.9, V12.9.86")
    monkeypatch.setenv("CUDA_HOME", str(root))
    assert benchmark._toolkit() == {"cuda_home": str(root), "cuda_home_ptxas_version": "12.9.86"}


def test_reports_without_a_pinned_toolkit_record_none(tmp_path, monkeypatch):
    monkeypatch.delenv("CUDA_HOME", raising=False)
    assert benchmark._toolkit() == {"cuda_home": None, "cuda_home_ptxas_version": None}
    monkeypatch.setenv("CUDA_HOME", str(tmp_path / "missing"))
    assert benchmark._toolkit() == {"cuda_home": str(tmp_path / "missing"), "cuda_home_ptxas_version": None}


def test_register_reports_read_the_ptx_isa_beside_each_ptxas_report(tmp_path):
    (tmp_path / "kernel_3.ptx").write_text("//\n// Generated by LLVM NVPTX Back-End\n//\n\n.version 8.8\n"
                                           ".target sm_90a\n.address_size 64\n")
    (tmp_path / "kernel_4.ptx").write_text(".target sm_90a\n")
    assert benchmark._ptx_isa(tmp_path / "kernel_3.ptxas") == "8.8"
    assert benchmark._ptx_isa(tmp_path / "kernel_4.ptxas") is None
